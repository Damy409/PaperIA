mm_recall = recall_at_k(multimodal_retrieval, eval_df, TOP_K)
text_mrr = mean_reciprocal_rank(text_retrieval, eval_df)
mm_mrr = mean_reciprocal_rank(multimodal_retrieval, eval_df)

